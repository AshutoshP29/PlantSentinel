"""Maintenance work-order document (.docx) built with python-docx.

Content comes only from the database, the analytics result and the grounded recommendation.
Sections with no supported content say so explicitly instead of being filled in.
"""

from __future__ import annotations

import re
import uuid
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor

from app.agent.rag import Citation
from app.agent.schemas import Action, Recommendation

NOT_IN_SOURCES = "Not specified in the indexed manuals."
NO_SAFETY = (
    "No verified safety procedure was found in the indexed manuals. Follow the site permit-to-"
    "work and isolation procedure, and confirm precautions with the area authority before work."
)
PRIORITY_COLOURS = {
    "Emergency": RGBColor(0xB0, 0x00, 0x20),
    "High": RGBColor(0xC0, 0x50, 0x00),
    "Medium": RGBColor(0x8A, 0x6D, 0x00),
    "Low": RGBColor(0x2E, 0x6B, 0x30),
}


@dataclass
class WorkOrderData:
    asset: dict
    issue: str
    priority: str
    recommendation: Recommendation
    pattern: dict
    history: list[dict]
    citations: list[Citation]
    inspection: dict | None = None  # latest inspection (inspections.to_api shape)
    created: datetime = field(default_factory=datetime.now)
    work_order_id: str = ""

    def __post_init__(self) -> None:
        if not self.work_order_id:
            stamp = self.created.strftime("%Y%m%d")
            self.work_order_id = f"WO-AI-{stamp}-{self.asset['tag']}-{uuid.uuid4().hex[:4].upper()}"


def _refs(item: Action) -> str:
    return f"  [{', '.join(item.sources)}]" if item.sources else ""


def _heading(doc: Document, text: str) -> None:
    doc.add_heading(text, level=2)


def _bullets(doc: Document, items: list[str], style: str = "List Bullet") -> None:
    for text in items:
        doc.add_paragraph(text, style=style)


def _kv_table(doc: Document, rows: list[tuple[str, str]]) -> None:
    table = doc.add_table(rows=0, cols=2)
    table.style = "Light Grid Accent 1"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for k, v in rows:
        cells = table.add_row().cells
        cells[0].text, cells[1].text = k, v
        cells[0].paragraphs[0].runs[0].bold = True


def _failure_summary(pattern: dict) -> list[str]:
    m = pattern.get("matching") or pattern.get("all_work_orders") or {}
    if not m.get("events"):
        return ["No matching failure history recorded."]
    lines = [
        f"{m['events']} recorded events between {m.get('first')} and {m.get('last')}; "
        f"{m.get('events_in_window', 0)} since {pattern.get('window_start')}.",
    ]
    before, recent = m.get("mean_days_between_before_window"), m.get("mean_days_between_in_window")
    if before and recent:
        lines.append(f"Mean time between events fell from {before} days to {recent} days.")
    lines.append(
        f"Total downtime {m.get('total_downtime_hrs')} h; total cost INR "
        f"{m.get('total_cost_inr'):,}."
    )
    if pattern.get("keyword_filter"):
        lines.append(f"Filter applied to work-order text: {', '.join(pattern['keyword_filter'])}.")
    lines.append(f"Method: {pattern.get('method', 'n/a')}.")
    return lines


def build_work_order(wo: WorkOrderData, out_dir: Path) -> Path:
    rec = wo.recommendation
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(10.5)

    title = doc.add_heading("Maintenance Work Order", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p = doc.add_paragraph()
    p.add_run(f"{wo.work_order_id}    ").bold = True
    run = p.add_run(f"Priority: {wo.priority}")
    run.bold = True
    run.font.color.rgb = PRIORITY_COLOURS.get(wo.priority, RGBColor(0, 0, 0))
    doc.add_paragraph(
        "Draft generated by PlantSentinel from plant records and indexed manuals. "
        "Must be reviewed and approved before execution."
    ).runs[0].italic = True

    a = wo.asset
    _heading(doc, "1. Equipment")
    _kv_table(
        doc,
        [
            ("Equipment ID", a["tag"]),
            ("Equipment", f"{str(a.get('type', '')).replace('_', ' ').title()} {a['tag']}"),
            ("Location / unit", str(a.get("location") or "-")),
            ("Criticality", str(a.get("criticality") or "-")),
            ("Installed", str(a.get("install_date") or "-")),
            ("Date raised", wo.created.strftime("%Y-%m-%d %H:%M")),
        ],
    )

    _heading(doc, "2. Reported issue")
    doc.add_paragraph(wo.issue)
    if rec.summary:
        doc.add_paragraph(rec.summary)

    _heading(doc, "3. Failure history")
    _bullets(doc, _failure_summary(wo.pattern))
    if wo.history:
        table = doc.add_table(rows=1, cols=4)
        table.style = "Light Grid Accent 1"
        for cell, text in zip(
            table.rows[0].cells, ("Work order", "Date", "Description", "Action taken"), strict=True
        ):
            cell.text = text
        for h in wo.history:
            cells = table.add_row().cells
            for cell, key in zip(cells, ("id", "date", "description", "action_taken"), strict=True):
                cell.text = str(h.get(key) or "")

    if wo.inspection:
        insp = wo.inspection
        doc.add_paragraph(
            f"Latest inspection {insp['id']} ({insp.get('date') or 'undated'}"
            + (f", report {insp['report_no']}" if insp.get("report_no") else "")
            + "):"
        )
        findings = insp.get("findings") or []
        _bullets(
            doc,
            [
                f"{x['item']}: {x['result']}" + (" (flagged)" if x.get("flagged") else "")
                for x in findings
            ]
            or ["No findings recorded."],
        )

    _heading(doc, "4. Probable causes and supporting evidence")
    if rec.probable_causes:
        _bullets(doc, [f"{c.cause}: {c.evidence}{_refs(c)}" for c in rec.probable_causes])
    else:
        doc.add_paragraph("No cause could be supported by the available sources.")

    _heading(doc, "5. Recommended maintenance actions")
    if rec.actions:
        _bullets(doc, [f"{x.action}{_refs(x)}" for x in rec.actions], "List Number")
    else:
        doc.add_paragraph(NOT_IN_SOURCES)

    _heading(doc, "6. Required materials")
    if rec.materials:
        _bullets(doc, [f"{x.action}{_refs(x)}" for x in rec.materials])
    else:
        doc.add_paragraph(NOT_IN_SOURCES)

    _heading(doc, "7. Safety precautions")
    if rec.safety:
        _bullets(doc, [f"{x.action}{_refs(x)}" for x in rec.safety])
    else:
        doc.add_paragraph(NO_SAFETY)

    _heading(doc, "8. Planning")
    duration = rec.estimated_duration
    reason = f" - {rec.priority_reason}" if rec.priority_reason else ""
    est = f"{duration.action}{_refs(duration)}" if duration else NOT_IN_SOURCES
    _kv_table(doc, [("Priority", f"{wo.priority}{reason}"), ("Estimated duration", est)])

    _heading(doc, "9. Manual references")
    if wo.citations:
        _bullets(doc, [f"[{c.ref}] {c.label()}" for c in wo.citations])
    else:
        doc.add_paragraph("None.")

    _heading(doc, "10. Approval")
    table = doc.add_table(rows=1, cols=4)
    table.style = "Light Grid Accent 1"
    for cell, text in zip(table.rows[0].cells, ("Role", "Name", "Signature", "Date"), strict=True):
        cell.text = text
    for role in ("Prepared by", "Reviewed by (Maintenance Engineer)", "Approved by (Area Manager)"):
        table.add_row().cells[0].text = role

    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{safe_filename(wo.work_order_id)}.docx"
    doc.save(str(path))
    return path


def safe_filename(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]", "_", name)
